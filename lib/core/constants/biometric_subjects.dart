  /// تصفية المواد حسب القسم والمرحلة والكورس
  static List<SubjectModel> getSubjects({
    String? department,
    String? stage,
    int? semester,
  }) {
    return allSubjects.where((s) {
      if (department != null && department != 'ALL') {
        final matchDept = s.departmentName == department ||
            s.departmentName.contains(department) ||
            department.contains(s.departmentName);
        if (!matchDept) return false;
      }
      if (stage != null && stage != 'ALL') {
        final matchStage = s.stageName == stage ||
            s.stageName.contains(stage) ||
            stage.contains(s.stageName);
        if (!matchStage) return false;
      }
      if (semester != null && semester != 0) {
        if (s.semester != semester) return false;
      }
      return true;
    }).toList();
  }

  /// استرجاع أسماء المواد فقط
  static List<String> getSubjectNames({
    String? department,
    String? stage,
    int? semester,
  }) {
    final res = getSubjects(
      department: department,
      stage: stage,
      semester: semester,
    ).map((s) => s.name).toSet().toList();
    return res;
  }

  /// خريطة المقررات الكاملة لكل قسم ومرحلة معتمدة من نظام البصمة
  static Map<String, Map<String, List<String>>> buildCurriculumMap() {
    final Map<String, Map<String, List<String>>> map = {};
    for (final s in allSubjects) {
      map.putIfAbsent(s.departmentName, () => {});
      map[s.departmentName]!.putIfAbsent(s.stageName, () => []);
      if (!map[s.departmentName]![s.stageName]!.contains(s.name)) {
        map[s.departmentName]![s.stageName]!.add(s.name);
      }
    }
    return map;
  }
